select p.product_name, count(p.product_id) as total_orders,
sum(case when o.status='Cancelled' then 1 else 0 end) as cancelled_orders,
sum(case when o.status='Cancelled' then 1 else 0 end)/count(p.product_id)*100 as cancellation_rate
from products p  inner join orders o 
on p.product_id=o.product_id
group by p.product_id,p.product_name
order by cancellation_rate desc;
/* cancellation rate= cancelled order/ total order * 100,
cancellation rate gives a better idea in terms of %, What proportion of placed orders were cancelled.,
we can categorize the customer as serious buyer or not, or level of commitment etc. 
high cancellation rate tells a lot, it might me about customer behaviuor, or the frictions they might be facing somewhere in the funnel,
