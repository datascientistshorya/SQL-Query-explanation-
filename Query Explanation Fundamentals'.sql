/*Q1 — Customer Revenue
Calculate completed revenue for each customer.
Return:
customer_name
completed_revenue

Requirements:
Only Completed orders
Include customers with no completed orders
Show 0 for customers with no completed revenue
Sort by completed_revenue descending

After writing the SQL, explain:
Why you chose the join type
Where you applied the status filter
Why GROUP BY is required
Why COALESCE() is used*/
select c.customer_id,c.customer_name,COALESCE(sum(o.amount), 0) AS completed_revenue
from customers c left join orders o 
on c.customer_id=o.customer_id
AND o.status = 'Completed'
group by c.customer_id,c.customer_name;

/* we choose Left join to show customers even with no completed orders, filtered rows where status was'Completed' as we needed rows
for completed orders, group by is not required to aggregate data per customer, COALESCE is used to replace null values with 
0 if any such customers exists.*/

