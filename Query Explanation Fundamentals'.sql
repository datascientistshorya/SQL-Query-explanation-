/*Q4 — Cancellation Rate by City
Calculate the cancellation rate for each city.
Return:
•	city 
•	total_orders 
•	cancelled_orders 
•	cancellation_rate 
Use:
Cancellation Rate = Cancelled Orders / Total Orders × 100
Requirements:
•	Include cities with orders 
•	Sort by cancellation_rate descending 
After writing the SQL, explain:
•	How you calculate total orders 
•	How you calculate cancelled orders 
•	Why total orders are the denominator 
•	What a high cancellation rate tells an analyst*/

select c.city,count(o.order_id) as total_orders,
sum(case when o.status='Cancelled' then 1 else 0 end) as cancelled_orders,
sum(case when o.status='Cancelled' then 1 else 0 end)/count(o.order_id) *100 as cancellation_rate
from customers c inner join orders o 
on c.customer_id=o.customer_id
group by c.city
order by cancellation_rate desc;
/* count(o.order_id) is used to calculate the total orders
	using case and applying condition as cancelled we calculated no. of cancelled orders
    total orders are the denominator because we need to calculate %, any no/total is the way to calculate %
    high cancellation rates tells analysts which cities are prone to high cancellation and take the appropriate business action*/
    
/*Q5 — Customer Order Behavior
For every customer, calculate:
•	customer_name 
•	total_orders 
•	completed_orders 
•	cancelled_orders 
•	total_revenue 
Requirements:
•	Revenue should come only from completed orders 
•	Include customers with no orders 
•	Sort by total_revenue descending 
After writing the SQL, explain:
•	How multiple metrics are calculated from the same order table 
•	How you prevent cancelled orders from contributing to revenue 
•	How customers with no orders are retained 
•	Why this query is useful for customer analysis*/

select c.customer_name,count(o.order_id) as total_orders,
sum(case when o.status='Cancelled' then 1 else 0 end) as cancelled_orders,
sum(case when o.status='Completed' then 1 else 0 end) as completed_orders,
sum(case when o.status='Completed' then o.amount else 0 end) as completed_revenue
from customers c left join orders o 
on c.customer_id=o.customer_id
group by c.customer_id,c.customer_name
order by completed_revenue desc;
/* count(o.order_id) for total orders, case with appropriate conditions for other metrics,
customers with no orders are retained by using a left join
this query is useful for customer analysis, like customer behaviuor, total conversion, serious buyers etc*/

/*Q6 — Product Cancellation Analysis
Analyze cancellation behavior for every product.
